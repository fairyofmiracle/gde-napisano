"""Переформулировка вопроса для повторного поиска: правила (без модели) и разбор ответа модели."""
from __future__ import annotations

import re

from app.text import normalize

# Вежливые и разговорные слова, которые только мешают поиску по словам
_FILLERS = re.compile(
    r"\b(?:подскажите|подскажи|скажите|скажи|пожалуйста|плиз|пжл|будьте добры|"
    r"а|ну|вот|короче|типа|как бы|вообще|у нас|в нашей компании|в компании|мне|меня|я|хочу узнать|"
    r"интересует|вопрос такой|здравствуйте|привет|добрый день|спасибо)\b", re.I)

# Разговорное слово → как это обычно называется в регламентах. Ключ — начало слова.
SYNONYMS: dict[str, str] = {
    "зп": "заработная плата",
    "зарплат": "заработная плата",
    "больничн": "листок нетрудоспособности",
    "отгул": "день отдыха",
    "отпускн": "оплата отпуска",
    "декрет": "отпуск по беременности и родам отпуск по уходу за ребёнком",
    "уволит": "увольнение расторжение трудового договора",
    "увольнят": "увольнение расторжение трудового договора",
    "удалёнк": "дистанционная работа",
    "удаленк": "дистанционная работа",
    "переработ": "сверхурочная работа",
    "командировочн": "суточные командировка",
    "ноут": "ноутбук компьютерное оборудование",
    "комп": "компьютер оборудование",
    "впн": "VPN удалённый доступ",
    "vpn": "удалённый доступ",
    "пропуск": "пропуск доступ в здание",
    "такси": "транспортные расходы",
    "чек": "кассовый чек подтверждающие документы",
    "обед": "перерыв для отдыха и питания",
    "опозда": "нарушение трудовой дисциплины",
    "почт": "электронная почта",
    "пароль": "пароль учётная запись",
    "флешк": "съёмный носитель",
    "справк": "справка выдача документов",
}

_WORD = re.compile(r"[\w-]+", re.U)


def _clean(question: str) -> str:
    q = _FILLERS.sub(" ", question)
    q = re.sub(r"[!?.…,;:]+", " ", q)
    return re.sub(r"\s+", " ", q).strip()


def rule_rewrite(question: str) -> str:
    """Вопрос без вежливых слов плюс официальные термины для разговорных слов.
    Пустая строка — правилам нечего добавить, повторный поиск не нужен."""
    base = _clean(question)
    low = normalize(base)
    extra: list[str] = []
    for word in _WORD.findall(low):
        for key, official in SYNONYMS.items():
            if word.startswith(key) and normalize(official) not in low and official not in extra:
                extra.append(official)
    out = " ".join([base, *extra]).strip()
    if not out or normalize(out) == normalize(question.strip(" ?!.")):
        return ""
    return out


def split_question(question: str) -> list[str]:
    """Составной вопрос («…? И ещё …?») делим на части; одна часть — пустой список."""
    parts = [p.strip() for p in re.split(r"[?;]+|\s+а\s+ещё\s+|\s+и\s+ещё\s+", question) if p.strip()]
    parts = [p for p in parts if len(_WORD.findall(p)) >= 2]
    return parts if len(parts) >= 2 else []
